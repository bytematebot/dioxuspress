//! Codegen: `docs/` becomes a `Route` enum, a component per page, and nav tables.
//!
//! The output goes to `generated/docs.rs`, where `dx` can watch it and hot-reload
//! content edits without a rebuild.

mod rsx;

use crate::core::ast::TocEntry;
use crate::core::config::Config;
use crate::core::site::{self, Page, SidebarNode, Site};
use anyhow::{Context, Result};
use proc_macro2::{Span, TokenStream};
use quote::quote;
use rsx::{lit, raw_lit};
use std::path::{Path, PathBuf};
use syn::Ident;

/// Where the generated module lives, relative to the project root. Not under `src/`,
/// and not hidden: `dx` ignores dotted directories and gives them no hot reload.
pub const GENERATED_PATH: &str = "generated/docs.rs";

/// Regenerates `generated/docs.rs`, returning its path and whether it changed. Identical
/// content leaves the file untouched, so watching it does not feed itself.
pub fn generate_to_file(root: &Path) -> Result<(PathBuf, bool)> {
    let generated = generate(root)?;
    let path = root.join(GENERATED_PATH);

    if let Ok(existing) = std::fs::read_to_string(&path) {
        if existing == generated {
            return Ok((path, false));
        }
    }

    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("creating {}", parent.display()))?;
    }
    std::fs::write(&path, generated).with_context(|| format!("writing {}", path.display()))?;
    Ok((path, true))
}

/// Generates the site module as formatted Rust source.
pub fn generate(root: &Path) -> Result<String> {
    let config = Config::load(root)?;
    let languages = crate::core::lang::load(root)?;
    let site = site::load(
        &config.docs_path(root),
        &config.normalized_base(),
        &languages,
    )?;
    let tokens = module(&config, &site)?;
    Ok(render(tokens))
}

/// Formats via `prettyplease`, falling back to raw tokens on a codegen bug.
fn render(tokens: TokenStream) -> String {
    let body = match syn::parse2::<syn::File>(tokens.clone()) {
        Ok(file) => prettyplease::unparse(&file),
        Err(_) => tokens.to_string(),
    };
    format!("// Generated by dioxus-press. Do not edit.\n{body}")
}

fn module(config: &Config, site: &Site) -> Result<TokenStream> {
    let site_config = site_config(config);
    let sidebar = sidebar_tokens(&site.sidebar);
    let pages = pages_tokens(&site.pages);
    let route_enum = route_enum(&site.pages, config.has_landing());
    let components = site
        .pages
        .iter()
        .map(page_component)
        .collect::<Result<Vec<_>>>()?;

    let landing_import = if config.has_landing() {
        quote! { use crate::landing::Landing; }
    } else {
        TokenStream::new()
    };

    Ok(quote! {
        #![allow(non_snake_case, unused_imports, unused_variables, clippy::all)]

        use dioxus::prelude::*;
        use dioxus_router::{Outlet, Routable};
        use dioxus_press::types::{PageMeta, SidebarItem, SiteConfig, Tasks, TocItem, Token};
        use crate::theme::*;
        use crate::components::*;
        #landing_import

        pub const SITE_CONFIG: SiteConfig = #site_config;

        // Must stay a function: hot-patching swaps code, so a static would go stale.
        pub fn sidebar() -> &'static [SidebarItem] {
            #sidebar
        }

        pub fn pages() -> &'static [PageMeta] {
            #pages
        }

        #route_enum

        /// Wraps every page in the documentation chrome.
        #[component]
        pub fn DocsShell() -> Element {
            rsx! {
                DocsChrome {
                    config: SITE_CONFIG,
                    sidebar: sidebar(),
                    pages: pages(),
                    Outlet::<Route> {}
                }
            }
        }

        #[component]
        pub fn NotFound(segments: Vec<String>) -> Element {
            rsx! {
                h1 { "404" }
                p { "That page does not exist." }
                DocLink { route: SITE_CONFIG.docs_root, class: "", "Back to the docs" }
            }
        }

        #(#components)*
    })
}

fn site_config(config: &Config) -> TokenStream {
    let title = raw_lit(&config.title);
    let description = option_str(config.description.as_deref());
    let repository = option_str(config.repository.as_deref());
    let docs_root = raw_lit(&config.docs_root());
    quote! {
        SiteConfig {
            title: #title,
            description: #description,
            repository: #repository,
            docs_root: #docs_root,
        }
    }
}

fn option_str(value: Option<&str>) -> TokenStream {
    match value {
        Some(value) => {
            let value = raw_lit(value);
            quote! { Some(#value) }
        }
        None => quote! { None },
    }
}

fn sidebar_tokens(nodes: &[SidebarNode]) -> TokenStream {
    let items = nodes.iter().map(|node| match node {
        SidebarNode::Link { title, route } => {
            let (title, route) = (raw_lit(title), raw_lit(route));
            quote! { SidebarItem { title: #title, route: Some(#route), items: &[] } }
        }
        SidebarNode::Group {
            title,
            route,
            items,
        } => {
            let title = raw_lit(title);
            let route = option_str(route.as_deref());
            let items = sidebar_tokens(items);
            quote! { SidebarItem { title: #title, route: #route, items: #items } }
        }
    });
    quote! { &[ #(#items),* ] }
}

fn pages_tokens(pages: &[Page]) -> TokenStream {
    let pages = pages.iter().map(|page| {
        let route = raw_lit(&page.route);
        let title = raw_lit(&page.title);
        let description = option_str(page.description.as_deref());
        let toc = toc_tokens(&page.doc.toc);
        let text = raw_lit(&page.doc.plain_text);
        let pager = page.doc.frontmatter.pager && !page.hidden;
        let (done, total) = (
            proc_macro2::Literal::u32_suffixed(page.doc.tasks.done),
            proc_macro2::Literal::u32_suffixed(page.doc.tasks.total),
        );
        quote! {
            PageMeta {
                route: #route,
                title: #title,
                description: #description,
                toc: #toc,
                text: #text,
                pager: #pager,
                tasks: Tasks { done: #done, total: #total },
            }
        }
    });
    quote! { &[ #(#pages),* ] }
}

fn toc_tokens(entries: &[TocEntry]) -> TokenStream {
    let entries = entries.iter().map(|entry| {
        let (id, title, level) = (
            raw_lit(&entry.id),
            raw_lit(&entry.title),
            proc_macro2::Literal::u8_suffixed(entry.level),
        );
        quote! { TocItem { id: #id, title: #title, level: #level } }
    });
    quote! { &[ #(#entries),* ] }
}

fn route_enum(pages: &[Page], landing: bool) -> TokenStream {
    let variants = pages.iter().map(|page| {
        let ident = Ident::new(&page.ident, Span::call_site());
        let route = raw_lit(&page.route);
        quote! {
            #[route(#route)]
            #ident {},
        }
    });

    let landing = if landing {
        quote! {
            #[route("/")]
            Landing {},
        }
    } else {
        TokenStream::new()
    };

    quote! {
        #[derive(Clone, Debug, PartialEq, Routable)]
        #[rustfmt::skip]
        pub enum Route {
            #landing
            #[layout(DocsShell)]
            #(#variants)*
            #[route("/:..segments")]
            NotFound { segments: Vec<String> },
        }
    }
}

fn page_component(page: &Page) -> Result<TokenStream> {
    let ident = Ident::new(&page.ident, Span::call_site());
    let body = rsx::children(&page.doc.nodes)
        .with_context(|| format!("generating {}", page.file.display()))?;
    let source = lit(&page.file.display().to_string());
    Ok(quote! {
        #[doc = "Generated from the markdown source."]
        #[component]
        pub fn #ident() -> Element {
            let _source = #source;
            rsx! { #body }
        }
    })
}
